"""Issue #2216: when a schema-sync check fails, the CI-repair context delivered
to the agent must include the FULL schema diff (not the failure-marker-filtered
excerpt that strips diff lines) plus a rule telling the agent to mirror the
regenerated bytes / run rebuild instead of hand-editing.

Mirrors tests/issues/1855 (_make_orchestrator pattern).
"""

from unittest.mock import MagicMock, patch

import pytest

pytestmark = [pytest.mark.regression, pytest.mark.issue(2216)]


def _make_workflow(**overrides):
    base = {
        "workflow_id": "wf-2216",
        "user_id": 1,
        "status": "merging",
        "current_phase": "merge",
        "branch_name": "auto-dev/wf-2216",
        "branch_strategy": "worktree",
        "worktree_path": "/tmp/repo",
        "preferred_worktree_path": "/tmp/repo",
        "dev_round": 1,
    }
    base.update(overrides)
    return base


def _make_orchestrator(wf_data):
    from app.modules.workspace.autonomous.orchestrator import AutonomousOrchestrator

    with (
        patch("app.modules.workspace.autonomous.orchestrator.Database"),
        patch(
            "app.modules.workspace.autonomous.orchestrator.AutonomousWorkflowRepository"
        ) as mock_repo_cls,
    ):
        mock_repo = MagicMock()
        mock_repo.list_milestones.return_value = []
        mock_repo.create_milestone.return_value = {"milestone_id": "ms-1"}
        mock_repo.create_event.return_value = {"id": 1}
        mock_repo_cls.return_value = mock_repo
        orch = AutonomousOrchestrator(wf_data["workflow_id"])
        orch.repo = mock_repo
        orch.emitter = MagicMock()
        orch._sync_failed_pr_with_main = MagicMock(return_value=False)
    return orch


_SCHEMA_DIFF_LOG = (
    "::error::Schema snapshots are out of sync with migrations (byte-exact).\n"
    "===== FULL DIFF =====\n"
    "diff --git a/schema/schema-sqlite.sql b/schema/schema-sqlite.sql\n"
    "--- a/schema/schema-sqlite.sql\n"
    "+++ b/schema/schema-sqlite.sql\n"
    "@@ -1815,7 +1815,7 @@\n"
    "-CREATE INDEX idx_teams_sync_source ON teams ((json_extract(settings, '$.sync_source')));\n"
    "+CREATE INDEX idx_teams_sync_source ON teams (((json_extract(settings, '$.sync_source'))));\n"
    "===== END DIFF =====\n"
    "Fix: the '+' lines above ARE the correct regenerated content.\n"
)


def test_schema_sync_failure_includes_full_diff_in_context():
    """The agent's CI-repair context must carry the schema diff verbatim.

    The enrichment loop in _start_ci_repair_round pre-populates
    ``failure_excerpt`` on each failed check (fetching UNFILTERED for
    schema-sync, #2216). _build_ci_repair_context then passes that
    pre-populated excerpt through and appends the schema-sync rule. This test
    drives _build_ci_repair_context directly with a pre-populated excerpt to
    mirror the real data flow (where the enrichment loop has already run).
    """
    wf = _make_workflow()
    orch = _make_orchestrator(wf)
    gh = MagicMock()
    gh.get_pr_head_sha.return_value = "sha"
    # Simulate the enrichment loop having already fetched the UNFILTERED excerpt
    # onto the check (PR #2255 review B1: this is the real production data flow).
    failed = [
        {
            "name": "schema-sync",
            "state": "failure",
            "bucket": "fail",
            "link": "https://github.com/open-ace/open-ace/runs/1",
            "failure_excerpt": _SCHEMA_DIFF_LOG,
        }
    ]

    ctx = orch._build_ci_repair_context(wf, gh, 2216, failed)

    # The diff body (which _FAILURE_LINE_RE would strip) must survive into the context
    assert "idx_teams_sync_source" in ctx, "schema diff must reach the agent"
    assert "(((json_extract" in ctx, "regenerated '+' content must be present"
    # The schema-sync rule must be appended
    assert "rebuild_schema_snapshots" in ctx
    assert "不要手编" in ctx or "不要手动编辑" in ctx
    # _build_ci_repair_context must NOT re-fetch (it consumes the pre-populated
    # excerpt); this guards against reintroducing the dead else-branch (#2255 B1).
    gh.get_check_failure_excerpt.assert_not_called()


def test_enrichment_loop_fetches_unfiltered_for_schema_sync():
    """The enrichment loop (_start_ci_repair_round) must fetch the schema-sync
    check's log UNFILTERED so the diff reaches both the agent context and the
    failure fingerprint.

    This drives the REAL data flow end-to-end through the enrichment loop
    (the production code path), not just _build_ci_repair_context. It would
    have caught PR #2255 review B1, where the unfiltered fetch lived only in
    a dead else-branch of _build_ci_repair_context.
    """
    wf = _make_workflow(
        ci_repair_attempts=1,
        ci_repair_transient_retries=0,
        ci_diagnostics_attempts=0,
        last_ci_failure_signature="",
        last_ci_failure_head_sha="",
    )
    orch = _make_orchestrator(wf)
    gh = MagicMock()
    gh.get_pr_head_sha.return_value = "sha-new"
    # Enrichment loop fetches the (unfiltered) diff body for schema-sync
    gh.get_check_failure_excerpt.return_value = _SCHEMA_DIFF_LOG
    orch._get_gh = MagicMock(return_value=gh)
    orch._run_merge_ci_repair = MagicMock()

    failed = [
        {
            "name": "schema-sync",
            "state": "failure",
            "bucket": "fail",
            "link": "https://github.com/open-ace/open-ace/runs/1",
        }
    ]

    orch._start_ci_repair_round(wf, 2216, failed)

    # The schema-sync check must have been fetched UNFILTERED (filter_lines=False).
    calls = gh.get_check_failure_excerpt.call_args_list
    assert calls, "enrichment loop must fetch failure excerpts"
    assert any(
        call.kwargs.get("filter_lines") is False for call in calls
    ), "schema-sync must be fetched with filter_lines=False (PR #2255 B1)"


def test_non_schema_sync_failure_uses_filtered_excerpt():
    """A non-schema-sync failure must still use the filtered excerpt (no noise)."""
    wf = _make_workflow()
    orch = _make_orchestrator(wf)
    gh = MagicMock()
    gh.get_check_failure_excerpt.return_value = "some lint failure\nno diff here"
    failed = [
        {
            "name": "lint",
            "state": "failure",
            "bucket": "fail",
            "link": "https://github.com/open-ace/open-ace/runs/2",
        }
    ]

    ctx = orch._build_ci_repair_context(wf, gh, 2216, failed)

    assert "rebuild_schema_snapshots" not in ctx, "schema-sync rule must not fire for lint"
    # The filtered excerpt path was used (get_check_failure_excerpt called with default filter)
    gh.get_check_failure_excerpt.assert_called()
    # filter_lines kwarg NOT passed (defaults True) for non-schema-sync
    for call in gh.get_check_failure_excerpt.call_args_list:
        assert call.kwargs.get("filter_lines", True) is True


def test_get_check_failure_excerpt_unfiltered_keeps_diff_lines():
    """Unit-test the github_ops unfiltered path directly: filter_lines=False must
    NOT strip non-failure-marker lines (the diff body)."""
    from app.modules.workspace.autonomous.github_ops import GitHubOps

    raw = "::error::x\n" + _SCHEMA_DIFF_LOG  # contains diff lines w/o failure markers
    ops = GitHubOps.__new__(GitHubOps)
    filtered = ops._clean_log_to_excerpt(raw, max_lines=80, max_chars=4000, filter_lines=True)
    unfiltered = ops._clean_log_to_excerpt(raw, max_lines=80, max_chars=4000, filter_lines=False)
    assert "(((json_extract" not in filtered, "filtered path strips the diff (the bug)"
    assert "(((json_extract" in unfiltered, "unfiltered path must keep the diff"
